from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

BASE = "2026-11-09T07:00:00Z"


def eml(sender: str, recipient: str, mid: str, subject: str, body: str,
        reply: str | None = None, date: str = "Mon, 09 Nov 2026 07:00:00 +0000") -> bytes:
    fields = [f"From: {sender}", f"To: {recipient}", f"Date: {date}",
              f"Message-ID: <{mid}>", f"Subject: {subject}"]
    if reply is not None:
        fields.append(f"In-Reply-To: <{reply}>")
    return ("\r\n".join(fields) + "\r\n\r\n" + body).encode("utf-8")


def cases() -> list[tuple[str, bytes, dict]]:
    a = eml("alice@example.invalid", "bob@example.invalid", "root@example.invalid",
            "Synthetic request", "Hi Bob,\r\nPlease review the synthetic report.\r\nRegards,\r\nAlice\r\n")
    b = eml("bob@example.invalid", "alice@example.invalid", "reply@example.invalid",
            "Re: Synthetic request", "I will review it.\r\n> Please review the synthetic report.\r\n",
            reply="root@example.invalid")
    c = eml("carol@example.invalid", "alice@example.invalid", "forward@example.invalid",
            "Fwd: Synthetic request", "See below.\r\n---------- Forwarded message ---------\r\nFrom: alice@example.invalid\r\nPlease review the synthetic report.\r\n")
    d = eml("bob@example.invalid", "alice@example.invalid", "reply@example.invalid",
            "Re: Synthetic request", "A conflicting claimed Message-ID, not a duplicate.\r\n")
    return [
        ("root", a, {"case": "synthetic-work-1", "role": "source", "claimed_parent": None}),
        ("reply", b, {"case": "synthetic-work-1", "role": "reply", "claimed_parent": "root"}),
        ("forward", c, {"case": "synthetic-work-1", "role": "forward", "claimed_parent": None}),
        ("conflicting_id", d, {"case": "synthetic-work-2", "role": "conflicting_claim", "claimed_parent": None}),
    ]


def perturbations() -> list[tuple[str, str, bytes, str]]:
    originals = {name: raw for name, raw, _ in cases()}
    return [
        ("date_shift", "root", originals["root"].replace(
            b"Mon, 09 Nov 2026 07:00:00 +0000", b"Mon, 09 Nov 2026 08:00:00 +0000"),
         "header_date_changed_not_observed_at"),
        ("reply_target_missing", "reply", originals["reply"].replace(
            b"In-Reply-To: <root@example.invalid>", b"In-Reply-To: <missing@example.invalid>"),
         "reply_candidate_should_abstain"),
        ("quoted_request", "reply", originals["reply"].replace(
            b"> Please review the synthetic report.", b">> Please review the synthetic report."),
         "quote_depth_changed_not_new_request"),
        ("recipient_changed", "root", originals["root"].replace(
            b"To: bob@example.invalid", b"To: carol@example.invalid"),
         "header_recipient_changed_not_task_actor"),
        ("message_id_collision", "forward", originals["forward"].replace(
            b"Message-ID: <forward@example.invalid>", b"Message-ID: <root@example.invalid>"),
         "ambiguous_claimed_identifier"),
    ]


def manifest() -> dict:
    rows = []
    for name, raw, truth in cases():
        rows.append({"name": name, "file": f"raw/{name}.eml",
                     "sha256": hashlib.sha256(raw).hexdigest(),
                     "bytes": len(raw), "construction_truth": truth})
    changes = []
    for name, original, raw, expected in perturbations():
        changes.append({"name": name, "source": original, "file": f"perturbed/{name}.eml",
                        "sha256": hashlib.sha256(raw).hexdigest(), "bytes": len(raw),
                        "expected_invariant": expected})
    return {"schema_version": "1.0.0", "synthetic_only": True,
            "observed_at": BASE, "originals": rows, "perturbations": changes,
            "provenance": "Original fictional fixture generated by mailweft scripts/synthetic_mime.py"}


def write(root: Path) -> None:
    root.mkdir(parents=True, exist_ok=True)
    for name, raw, _ in cases():
        dest = root / "raw" / f"{name}.eml"
        dest.parent.mkdir(exist_ok=True)
        dest.write_bytes(raw)
    for name, _, raw, _ in perturbations():
        dest = root / "perturbed" / f"{name}.eml"
        dest.parent.mkdir(exist_ok=True)
        dest.write_bytes(raw)
    (root / "manifest.json").write_text(json.dumps(manifest(), indent=2, sort_keys=True) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    write(args.output)


if __name__ == "__main__":
    main()
